#!/usr/bin/env bash
set -euo pipefail

# Run generated fio workloads against the Linux baseline and dispatcher-loaded
# a_* policies. This runner keeps the baseline/policy fio invocation identical
# except for the external policy loader, records cgroup/iostat/time-series data,
# and samples fio/dispatcher/loader CPU independently.

SUPPORTED_POLICIES=(fifo s3fifo lfu lru arc)
SUPPORTED_PRESSURES=(all low medium high)

CGROUP_NAME="cache_ext_test"
CGROUP_PATH="/sys/fs/cgroup/$CGROUP_NAME"
BASELINE_CGROUP_NAME="baseline_test"
BASELINE_CGROUP_PATH="/sys/fs/cgroup/$BASELINE_CGROUP_NAME"
DISPATCHER_CPU_CGROUP_NAME="cache_ext_dispatcher_monitor"
DISPATCHER_CPU_CGROUP_PATH="/sys/fs/cgroup/$DISPATCHER_CPU_CGROUP_NAME"
LOADER_CPU_CGROUP_NAME="cache_ext_loader_monitor"
LOADER_CPU_CGROUP_PATH="/sys/fs/cgroup/$LOADER_CPU_CGROUP_NAME"
REGISTRY_PATH="/sys/fs/bpf/dispatcher_registry"
BPF_PIN_DIR="/sys/fs/bpf/cache_ext"

SCRIPT_PATH=$(realpath "$0")
SCRIPT_DIR=$(realpath "$(dirname "$SCRIPT_PATH")")
BASE_DIR=$(realpath "$SCRIPT_DIR/../..")
BENCH_PATH="$BASE_DIR/bench"
POLICY_PATH="$BASE_DIR/policies"
MONITOR_PATH="$SCRIPT_DIR/a_monitor_run.py"

TARGET_WORKLOAD="all"
TEST_POLICY="all"
PRESSURE_FILTER="all"
BENCH_DIR="$BASE_DIR/results/generated-fio-benches"
FIO_DIR="$BASE_DIR/results/fio_temp"
OUTPUT_ROOT="$BASE_DIR/results/a_fio_bench/$(date +%Y%m%d_%H%M%S)"
CPU_COUNT=8
ITERATIONS=3
RESET_FIO_DIR=false
ENABLE_TIME_SERIES=true
LOG_AVG_MSEC=1000
CPU_MONITOR_INTERVAL=1

DISPATCHER_PID=""
LOADER_PID=""
DISPATCHER_MONITOR_PID=""
LOADER_MONITOR_PID=""
CGROUP_MONITOR_PID=""
IOSTAT_MONITOR_PID=""
CPU_MONITOR_PID=""
WORKLOAD_COUNT=0

usage() {
    cat <<EOF
Usage: $0 [all|POLICY|BENCHMARK_ID] [options]

Run workloads generated by a_generate_fio_bench.sh.

Selector:
  all                         Run all manifest rows
  fifo|s3fifo|lfu|lru|arc      Run every pressure for that target benchmark family
  exact benchmark_id           Example: s3fifo_hot_cold_mix_medium

Options:
  --test-policy POLICY         Run baseline plus only this policy; default runs all policies
  --pressure LEVEL             all, low, medium, or high (default: $PRESSURE_FILTER)
  --bench-dir DIR              Generated benchmark directory (default: $BENCH_DIR)
  --fio-dir DIR                fio data directory (default: $FIO_DIR)
  --output-root DIR            Result/log directory (default: $OUTPUT_ROOT)
  --cpu N                      CPUs passed to a_bench_fio.py (default: $CPU_COUNT)
  --iterations N               Repetitions per baseline/policy (default: $ITERATIONS)
  --reset-fio-dir              Delete existing files in --fio-dir before running.
                               Use this after changing generated benchmark file sizes.
  --time-series                Write fio bw/iops/lat time-series logs (default)
  --no-time-series             Disable fio bw/iops/lat time-series logs
  --log-avg-msec N             fio time-series aggregation window in ms (default: $LOG_AVG_MSEC)
  --cpu-monitor-interval SEC   fio/dispatcher/loader CPU sample interval (default: $CPU_MONITOR_INTERVAL)
  -h, --help                   Show this help

Per-run directory artifacts:
  job_config.json
  benchmark_metadata.tsv
  run_metadata.txt
  cpu_usage.tsv
  cpu_cgroup.tsv
  policy_counters.tsv
  cgroup_before.txt / cgroup_first_seen.txt / cgroup_after.txt
  cgroup_memory.tsv
  iostat_x.log
  fio_iops.N.log / fio_lat.N.log / fio_bw.N.log when --time-series is enabled

Examples:
  bash eval/cpu-overhead/a_generate_fio_bench.sh all
  $0 s3fifo --test-policy s3fifo --pressure low --iterations 1
  $0 s3fifo_hot_cold_mix_medium --test-policy s3fifo --iterations 3
  $0 all --test-policy all --pressure high --iterations 3 --reset-fio-dir

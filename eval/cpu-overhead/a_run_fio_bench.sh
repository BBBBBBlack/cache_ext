run_workload() {
    local benchmark_id="$1"
    local target_policy="$2"
    local profile="$3"
    local pressure="$4"
    local runtime="$5"
    local warmup="$6"
    local measurement="$7"
    local cgroup_size="$8"
    local ioengine="$9"

die() {
    echo "[Error] $*" >&2
    exit 1
}

is_supported_policy() {
    case "$1" in
        fifo|s3fifo|lfu|lru|arc) return 0 ;;
        *) return 1 ;;
    esac
}

is_supported_pressure() {
    case "$1" in
        all|low|medium|high) return 0 ;;
        *) return 1 ;;
    esac
}

target_was_set=false
while [[ $# -gt 0 ]]; do
    case "$1" in
        --test-policy)
            [[ $# -ge 2 ]] || die "--test-policy requires a value"
            TEST_POLICY="$2"
            shift 2
            ;;
        --pressure)
            [[ $# -ge 2 ]] || die "--pressure requires a value"
            PRESSURE_FILTER="$2"
            shift 2
            ;;
        --bench-dir)
            [[ $# -ge 2 ]] || die "--bench-dir requires a value"
            BENCH_DIR="$2"
            shift 2
            ;;
        --fio-dir)
            [[ $# -ge 2 ]] || die "--fio-dir requires a value"
            FIO_DIR="$2"
            shift 2
            ;;
        --output-root)
            [[ $# -ge 2 ]] || die "--output-root requires a value"
            OUTPUT_ROOT="$2"
            shift 2
            ;;
        --cpu)
            [[ $# -ge 2 ]] || die "--cpu requires a value"
            CPU_COUNT="$2"
            shift 2
            ;;
        --iterations)
            [[ $# -ge 2 ]] || die "--iterations requires a value"
            ITERATIONS="$2"
            shift 2
            ;;
        --reset-fio-dir)
            RESET_FIO_DIR=true
            shift
            ;;
        --time-series)
            ENABLE_TIME_SERIES=true
            shift
            ;;
        --no-time-series)
            ENABLE_TIME_SERIES=false
            shift
            ;;
        --log-avg-msec)
            [[ $# -ge 2 ]] || die "--log-avg-msec requires a value"
            LOG_AVG_MSEC="$2"
            shift 2
            ;;
        --cpu-monitor-interval)
            [[ $# -ge 2 ]] || die "--cpu-monitor-interval requires a value"
            CPU_MONITOR_INTERVAL="$2"
            shift 2
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        -*)
            die "unknown option: $1"
            ;;
        *)
            $target_was_set && die "only one workload selector may be provided"
            TARGET_WORKLOAD="$1"
            target_was_set=true
            shift
            ;;
    esac
done

if [[ "$TEST_POLICY" != "all" ]] && ! is_supported_policy "$TEST_POLICY"; then
    die "unsupported test policy '$TEST_POLICY'"
fi
is_supported_pressure "$PRESSURE_FILTER" || \
    die "unsupported pressure '$PRESSURE_FILTER'; expected all, low, medium, or high"
[[ "$CPU_COUNT" =~ ^[1-9][0-9]*$ ]] || die "--cpu must be a positive integer"
[[ "$ITERATIONS" =~ ^[1-9][0-9]*$ ]] || die "--iterations must be a positive integer"
[[ "$LOG_AVG_MSEC" =~ ^[1-9][0-9]*$ ]] || die "--log-avg-msec must be a positive integer"
[[ "$CPU_MONITOR_INTERVAL" =~ ^[0-9]+([.][0-9]+)?$ ]] || \
    die "--cpu-monitor-interval must be a positive number"
awk -v value="$CPU_MONITOR_INTERVAL" 'BEGIN { exit !(value > 0) }' || \
    die "--cpu-monitor-interval must be > 0"

reset_fio_dir_if_requested() {
    $RESET_FIO_DIR || return 0

    local fio_abs
    local results_abs
    fio_abs=$(realpath -m "$FIO_DIR")
    results_abs=$(realpath -m "$BASE_DIR/results")

    if [[ "$fio_abs" == "/" || "$fio_abs" == "$results_abs" || "$fio_abs" != "$results_abs/"* ]]; then
        die "--reset-fio-dir refuses to clean outside $results_abs: $fio_abs"
    fi

    mkdir -p "$fio_abs"
    echo "[Info] resetting fio data directory: $fio_abs"
    find "$fio_abs" -mindepth 1 -maxdepth 1 -exec rm -rf -- {} +
}

for required in \
    "$BENCH_PATH/a_bench_fio.py" \
    "$POLICY_PATH/a_dispatcher.out" \
    "$POLICY_PATH/a_user_loader.out" \
    "$MONITOR_PATH" \
    "$BENCH_DIR/manifest.tsv"; do
    [[ -e "$required" ]] || die "required path does not exist: $required"
done

reset_fio_dir_if_requested
mkdir -p "$FIO_DIR" "$OUTPUT_ROOT"
cp -f "$BENCH_DIR/manifest.tsv" "$OUTPUT_ROOT/manifest.tsv"

read_cgroup_value() {
    local file="$1"
    if [[ -r "$file" ]]; then
        tr -d '\n' < "$file"
    else
        printf 'NA'
    fi
}

read_cgroup_multiline() {
    local file="$1"
    if [[ -r "$file" ]]; then
        tr '\n' ';' < "$file"
    else
        printf 'NA'
    fi
}

read_cgroup_stat_value() {
    local file="$1"
    local key="$2"
    local value
    if [[ -r "$file" ]]; then
        value=$(awk -v wanted="$key" '$1 == wanted { print $2; found=1; exit } END { if (!found) print "NA" }' "$file")
        printf '%s' "${value:-NA}"
    else
        printf 'NA'
    fi
}

write_cgroup_snapshot() {
    local cgroup_path="$1"
    local output_file="$2"
    local label="$3"

    {
        echo "label=$label"
        echo "timestamp=$(date -Is)"
        echo "path=$cgroup_path"
        if [[ -d "$cgroup_path" ]]; then
            echo "exists=true"
            for file_name in \
                memory.current \
                memory.max \
                memory.peak \
                memory.high \
                memory.low \
                memory.swap.current \
                memory.swap.max; do
                if [[ -e "$cgroup_path/$file_name" ]]; then
                    printf '%s=' "$file_name"
                    read_cgroup_value "$cgroup_path/$file_name"
                    printf '\n'
                fi
            done
            echo "[memory.events]"
            cat "$cgroup_path/memory.events" 2>/dev/null || true
            echo "[memory.stat]"
            cat "$cgroup_path/memory.stat" 2>/dev/null || true
            echo "[cgroup.procs]"
            cat "$cgroup_path/cgroup.procs" 2>/dev/null || true
        else
            echo "exists=false"
        fi
    } > "$output_file"
}

monitor_cgroup() {
    local cgroup_path="$1"
    local output_file="$2"
    local interval_seconds="$3"
    local first_seen_file="${4:-}"
    local first_seen=false

    {
        printf 'timestamp_iso\ttimestamp_sec\texists\tmemory_current\tmemory_max\tmemory_peak\tprocs\tmemory_events\tpgfault\tpgmajfault\tworkingset_refault_file\tworkingset_activate_file\n'
        while true; do
            local ts_iso
            local ts_epoch
            local exists
            local current
            local max
            local peak
            local procs
            local events
            local pgfault
            local pgmajfault
            local refault_file
            local activate_file

            ts_iso=$(date -Is)
            ts_epoch=$(date +%s)
            if [[ -d "$cgroup_path" ]]; then
                exists=true
                if [[ "$first_seen" == false && -n "$first_seen_file" ]]; then
                    write_cgroup_snapshot "$cgroup_path" "$first_seen_file" "first-seen"
                    first_seen=true
                fi
                current=$(read_cgroup_value "$cgroup_path/memory.current")
                max=$(read_cgroup_value "$cgroup_path/memory.max")
                peak=$(read_cgroup_value "$cgroup_path/memory.peak")
                procs=$(wc -l < "$cgroup_path/cgroup.procs" 2>/dev/null | tr -d ' ' || true)
                [[ -n "$procs" ]] || procs=NA
                events=$(read_cgroup_multiline "$cgroup_path/memory.events")
                pgfault=$(read_cgroup_stat_value "$cgroup_path/memory.stat" "pgfault")
                pgmajfault=$(read_cgroup_stat_value "$cgroup_path/memory.stat" "pgmajfault")
                refault_file=$(read_cgroup_stat_value "$cgroup_path/memory.stat" "workingset_refault_file")
                activate_file=$(read_cgroup_stat_value "$cgroup_path/memory.stat" "workingset_activate_file")
            else
                exists=false
                current=NA
                max=NA
                peak=NA
                procs=NA
                events=NA
                pgfault=NA
                pgmajfault=NA
                refault_file=NA
                activate_file=NA
            fi
            printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
                "$ts_iso" "$ts_epoch" "$exists" "$current" "$max" \
                "$peak" "$procs" "$events" "$pgfault" "$pgmajfault" \
                "$refault_file" "$activate_file"
            sleep "$interval_seconds"
        done
    } > "$output_file" 2>&1
}

stop_pid() {
    local pid="$1"
    if [[ -n "$pid" ]]; then
        kill "$pid" 2>/dev/null || true
        wait "$pid" 2>/dev/null || true
    fi
}

stop_cgroup_monitor() {
    stop_pid "$1"
}

start_iostat_monitor() {
    local output_file="$1"

    if command -v iostat >/dev/null 2>&1; then
        iostat -x -y -m 1 > "$output_file" 2>&1 &
        IOSTAT_MONITOR_PID=$!
        return 0
    fi

    {
        echo "# iostat is unavailable; recording /sys/block/*/stat once per second"
        echo -e "timestamp_iso\tdevice\treads_completed\tsectors_read\twrites_completed\tsectors_written\tio_ticks\tweighted_io_ticks"
        while true; do
            local timestamp
            timestamp=$(date -Is)
            for stat_file in /sys/block/*/stat; do
                [[ -r "$stat_file" ]] || continue
                local device
                device=$(basename "$(dirname "$stat_file")")
                read -r reads _ sectors_read _ writes _ sectors_written _ _ io_ticks weighted_io_ticks _ \
                    < "$stat_file" || true
                printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
                    "$timestamp" "$device" "${reads:-NA}" "${sectors_read:-NA}" \
                    "${writes:-NA}" "${sectors_written:-NA}" \
                    "${io_ticks:-NA}" "${weighted_io_ticks:-NA}"
            done
            sleep 1
        done
    } > "$output_file" 2>&1 &
    IOSTAT_MONITOR_PID=$!
}

stop_iostat_monitor() {
    stop_pid "$1"
}

start_cpu_monitor() {
    local cgroup_path="$1"
    local run_dir="$2"
    local mode="$3"
    local dispatcher_log="$run_dir/dispatcher.log"
    local loader_log="$run_dir/loader.log"
    local -a cmd=(
        python3 "$MONITOR_PATH"
        --cgroup-path "$cgroup_path"
        --cpu-output "$run_dir/cpu_usage.tsv"
        --cpu-cgroup-output "$run_dir/cpu_cgroup.tsv"
        --counter-output "$run_dir/policy_counters.tsv"
        --fio-cgroup-path "$cgroup_path"
        --interval "$CPU_MONITOR_INTERVAL"
    )

    if [[ "$mode" == "policy" ]]; then
        cmd+=(
            --dispatcher-pid "${DISPATCHER_MONITOR_PID:-$DISPATCHER_PID}"
            --loader-pid "${LOADER_MONITOR_PID:-$LOADER_PID}"
            --dispatcher-cgroup-path "$DISPATCHER_CPU_CGROUP_PATH"
            --loader-cgroup-path "$LOADER_CPU_CGROUP_PATH"
            --dispatcher-log "$dispatcher_log"
            --loader-log "$loader_log"
        )
    fi

    "${cmd[@]}" > "$run_dir/a_monitor_run.log" 2>&1 &
    CPU_MONITOR_PID=$!
}

stop_cpu_monitor() {
    stop_pid "$1"
}


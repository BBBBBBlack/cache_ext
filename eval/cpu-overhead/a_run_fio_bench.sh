    local working_set="${11}"
    local design_intent="${12}"
    local primary_group="${13}"
    local polluter_groups="${14}"
    local success_metric="${15}"
    local primary_rate_iops="${16}"
    local polluter_rate_iops="${17}"
    local primary_iops_share="${18}"
    local polluter_iops_share="${19}"
    local job_config_name="${20}"

    local job_file="$BENCH_DIR/$job_config_name"
    local workload_dir="$OUTPUT_ROOT/$benchmark_id"
    local iteration
    local result_file
    local run_log
    local baseline_dir

    [[ -r "$job_file" ]] || die "job config does not exist: $job_file"
    mkdir -p "$workload_dir"

    for ((iteration = 1; iteration <= ITERATIONS; iteration++)); do
        result_file="$workload_dir/${iteration}_baseline.json"
        run_log="$workload_dir/${iteration}_baseline.log"
        baseline_dir="$workload_dir/${iteration}_baseline"
        run_fio baseline "" "$runtime" "$warmup" "$measurement" \
            "$cgroup_size" "$ioengine" "$job_file" "$result_file" "$run_log" \
            "$baseline_dir" "$benchmark_id" "$target_policy" "$profile" \
            "$pressure" "$total_rate_iops" "$working_set" "$design_intent" \
            "$primary_group" "$polluter_groups" "$success_metric" \
            "$primary_rate_iops" "$polluter_rate_iops" \
            "$primary_iops_share" "$polluter_iops_share"

        for policy in "${policies_to_test[@]}"; do
            local policy_dir="$workload_dir/${iteration}_${policy}"
            mkdir -p "$policy_dir"
            start_external_policy "$policy" "$cgroup_size" "$policy_dir"
            result_file="$workload_dir/${iteration}_${policy}.json"
            run_log="$workload_dir/${iteration}_${policy}.log"
            run_fio policy "$policy" "$runtime" "$warmup" "$measurement" \
                "$cgroup_size" "$ioengine" "$job_file" "$result_file" \
                "$run_log" "$policy_dir" "$benchmark_id" "$target_policy" \
                "$profile" "$pressure" "$total_rate_iops" "$working_set" \

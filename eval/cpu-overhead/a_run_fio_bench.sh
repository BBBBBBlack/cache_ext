wait_for_pid() {
    local pid="$1"
    local description="$2"
    local attempt

    for attempt in {1..15}; do
        if ! sudo kill -0 "$pid" 2>/dev/null; then
            die "$description exited during startup; inspect its log"
        fi
        sleep 1
    done
}

resolve_monitor_pid() {
    local parent_pid="$1"
    local process_name="$2"
    local attempt
    local child_pid
    local children_file

    for attempt in {1..20}; do
        if command -v pgrep >/dev/null 2>&1; then
            child_pid=$(pgrep -P "$parent_pid" -f "$process_name" 2>/dev/null | head -n 1 || true)
            if [[ -n "$child_pid" ]]; then
                echo "$child_pid"
                return 0
            fi
        fi

        children_file="/proc/$parent_pid/task/$parent_pid/children"
        if [[ -r "$children_file" ]]; then
            child_pid=$(awk '{ print $1; exit }' "$children_file" 2>/dev/null || true)
            if [[ -n "$child_pid" ]]; then
                echo "$child_pid"
                return 0
            fi
        fi

        if [[ -r "/proc/$parent_pid/cmdline" ]] && tr '\0' ' ' < "/proc/$parent_pid/cmdline" | grep -q "$process_name"; then
            echo "$parent_pid"
            return 0
        fi

        sleep 0.1
    done

    echo "$parent_pid"
}

prepare_process_monitor_cgroups() {
    sudo mkdir -p "$DISPATCHER_CPU_CGROUP_PATH" "$LOADER_CPU_CGROUP_PATH"
}

move_pid_to_cgroup() {
    local pid="$1"
    local cgroup_path="$2"
    local label="$3"

    [[ -n "$pid" ]] || return 0
    if [[ ! -d "$cgroup_path" ]]; then
        sudo mkdir -p "$cgroup_path"
    fi
    if ! sudo sh -c "echo '$pid' > '$cgroup_path/cgroup.procs'" 2>/dev/null; then
        echo "[Warn] could not move $label pid $pid to monitor cgroup $cgroup_path" >&2
    fi
}

prepare_external_cgroup() {
    local cgroup_size="$1"

    cleanup_external
    # cpu.stat is only useful when the cpu controller is delegated to the
    # child cgroups. Keep this best-effort because some hosts restrict
    # controller delegation; the monitor has a graceful fallback.
    sudo sh -c "echo '+memory +cpu' > /sys/fs/cgroup/cgroup.subtree_control" 2>/dev/null || \
        sudo sh -c "echo '+memory' > /sys/fs/cgroup/cgroup.subtree_control" 2>/dev/null || true
    sudo mkdir -p "$CGROUP_PATH"
    sudo sh -c "echo '$cgroup_size' > '$CGROUP_PATH/memory.max'"
}

start_external_policy() {
    local policy="$1"
    local cgroup_size="$2"
    local log_dir="$3"

    prepare_external_cgroup "$cgroup_size"
    prepare_process_monitor_cgroups
    mkdir -p "$log_dir"

    sudo "$POLICY_PATH/a_dispatcher.out" \
        -w "$FIO_DIR" \
        -c "$CGROUP_PATH" \
        > "$log_dir/dispatcher.log" 2>&1 &
    DISPATCHER_PID=$!
    wait_for_pid "$DISPATCHER_PID" "dispatcher"
    DISPATCHER_MONITOR_PID=$(resolve_monitor_pid "$DISPATCHER_PID" "a_dispatcher.out")
    move_pid_to_cgroup "$DISPATCHER_MONITOR_PID" "$DISPATCHER_CPU_CGROUP_PATH" "dispatcher"

    sudo "$POLICY_PATH/a_user_loader.out" \
        -c "$CGROUP_PATH" \
        -o "$policy" \
        > "$log_dir/loader.log" 2>&1 &
    LOADER_PID=$!
    wait_for_pid "$LOADER_PID" "loader"
    LOADER_MONITOR_PID=$(resolve_monitor_pid "$LOADER_PID" "a_user_loader.out")
    move_pid_to_cgroup "$LOADER_MONITOR_PID" "$LOADER_CPU_CGROUP_PATH" "loader"
}


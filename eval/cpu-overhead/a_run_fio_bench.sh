def to_float(value, default=math.nan):
    try:
        number = float(value)
    except (TypeError, ValueError):
        return default
    return number if math.isfinite(number) else default


def cpu_breakdown(path, warmup_seconds):
    roles = {"fio": [], "dispatcher": [], "loader": []}
    sample_count = {"fio": 0, "dispatcher": 0, "loader": 0}
    if path and os.path.exists(path):
        with open(path, "r", encoding="utf-8") as handle:
            reader = csv.DictReader(handle, delimiter="\t")
            for row in reader:
                role = row.get("role")
                if role not in roles:
                    continue
                ts = to_float(row.get("timestamp_sec"))
                if math.isfinite(warmup_seconds) and ts < warmup_seconds:
                    continue
                pct = to_float(row.get("cpu_pct"))
                if math.isfinite(pct):
                    roles[role].append(pct)
                    sample_count[role] += 1
    return {
        "steady_mean": {
            role: (sum(values) / len(values) if values else None)
            for role, values in roles.items()
        },
        "steady_sample_count": sample_count,
        "source": path,
    }


def cpu_cgroup_breakdown(path, warmup_seconds):
    roles = {"fio": [], "dispatcher": [], "loader": []}
    user = {"fio": [], "dispatcher": [], "loader": []}
    system = {"fio": [], "dispatcher": [], "loader": []}
    if path and os.path.exists(path):
        with open(path, "r", encoding="utf-8") as handle:
            reader = csv.DictReader(handle, delimiter="\t")
            for row in reader:
                role = row.get("role")
                if role not in roles:
                    continue
                ts = to_float(row.get("timestamp_sec"))
                if math.isfinite(warmup_seconds) and ts < warmup_seconds:
                    continue
                total_delta = to_float(row.get("usage_delta_usec"))
                user_delta = to_float(row.get("user_delta_usec"))
                system_delta = to_float(row.get("system_delta_usec"))
                if math.isfinite(total_delta):
                    roles[role].append(total_delta)
                if math.isfinite(user_delta):
                    user[role].append(user_delta)
                if math.isfinite(system_delta):
                    system[role].append(system_delta)
    return {
        "steady_total_usec": {role: sum(values) if values else None for role, values in roles.items()},
        "steady_user_usec": {role: sum(values) if values else None for role, values in user.items()},
        "steady_system_usec": {role: sum(values) if values else None for role, values in system.items()},
        "source": path,
    }


